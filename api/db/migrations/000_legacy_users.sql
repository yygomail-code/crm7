CREATE TABLE IF NOT EXISTS `users` (
  `ID` int NOT NULL AUTO_INCREMENT,
  `ACTIVE` enum('Y','N') DEFAULT 'Y',
  `TIME_ADD` timestamp NULL DEFAULT (now()),
  `SID` char(255) NOT NULL DEFAULT (uuid()),
  `LOGIN` char(255) DEFAULT NULL,
  `PASSWORD` char(255) DEFAULT NULL,
  `LEVEL` decimal(3,0) DEFAULT NULL,
  `TOKEN_TIME` char(255) DEFAULT NULL,
  `TOKEN_USER` char(255) DEFAULT NULL,
  `FULL_NAME` char(255) DEFAULT NULL,
  `STATUS` enum('Y','N') DEFAULT 'Y',
  `TIME_ACTIVE` timestamp NULL DEFAULT NULL,
  `NO_DELETE` enum('Y','N') DEFAULT 'N',
  `FNAME` char(255) DEFAULT NULL,
  `NNAME` char(255) DEFAULT NULL,
  `ONAME` char(255) DEFAULT NULL,
  `COMPANY` char(255) DEFAULT NULL,
  `DOLGNOST` char(255) DEFAULT NULL,
  `PHONE` char(255) DEFAULT NULL,
  `EMAIL` char(255) DEFAULT NULL,
  PRIMARY KEY (`ID`),
  UNIQUE KEY `SID` (`SID`),
  UNIQUE KEY `LOGIN` (`LOGIN`) USING BTREE,
  UNIQUE KEY `PHONE` (`PHONE`) USING BTREE,
  UNIQUE KEY `EMAIL` (`EMAIL`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
